import { describe, expect, it, vi } from 'vitest'
import { createSentryWelcome } from './sentryWelcome'

describe('Sentry welcome milestones', () => {
  it('waits for each real completion and the final milestone before showing the bubble', () => {
    const persist = vi.fn()
    const welcome = createSentryWelcome(false, persist)
    expect(welcome.get().cue).toBe(0)
    welcome.reveal()
    expect(welcome.get().cue).toBe(1)
    welcome.cueFinished(1)
    expect(welcome.get().cue).toBe(0)
    welcome.opened()
    expect(welcome.get().cue).toBe(2)
    welcome.cueFinished(2)
    expect(welcome.get().phase).toBe('pending')
    welcome.lastReady()
    expect(welcome.get().cue).toBe(3)
    expect(persist).not.toHaveBeenCalled()
    welcome.cueFinished(3)
    expect(welcome.get().phase).toBe('visible')
    expect(persist).toHaveBeenCalledOnce()
    welcome.dismiss()
    expect(welcome.get().phase).toBe('dismissed')
    expect(persist).toHaveBeenCalledOnce()
  })

  it('retains milestones arriving during an unfinished or paused gesture', () => {
    const welcome = createSentryWelcome(false, vi.fn())
    welcome.reveal()
    welcome.opened()
    welcome.lastReady()
    expect(welcome.get().cue).toBe(1)
    welcome.cueFinished(1)
    expect(welcome.get().cue).toBe(2)
    welcome.cueFinished(2)
    expect(welcome.get().cue).toBe(3)
    welcome.cueFinished(3)
    expect(welcome.get().phase).toBe('visible')
  })

  it('skips the zoom gesture when the intro is skipped or absent', () => {
    const welcome = createSentryWelcome(false, vi.fn())
    welcome.opened()
    expect(welcome.get().cue).toBe(2)
    welcome.cueFinished(2)
    welcome.lastReady()
    welcome.cueFinished(3)
    expect(welcome.get().phase).toBe('visible')
  })

  it('does not replay a seen welcome or notify for repeated milestones', () => {
    const welcome = createSentryWelcome(true, vi.fn())
    const listener = vi.fn()
    const off = welcome.subscribe(listener)
    welcome.reveal()
    welcome.opened()
    welcome.lastReady()
    welcome.cueFinished(3)
    welcome.dismiss()
    expect(welcome.get().phase).toBe('dismissed')
    expect(listener).not.toHaveBeenCalled()
    off()
  })

  it('ignores late completions after the visitor opens the chat', () => {
    const persist = vi.fn()
    const welcome = createSentryWelcome(false, persist)
    welcome.reveal()
    welcome.dismiss()
    welcome.opened()
    welcome.lastReady()
    welcome.cueFinished(1)
    expect(welcome.get()).toMatchObject({ phase: 'dismissed', cue: 0 })
    expect(persist).toHaveBeenCalledOnce()
  })

  it('ignores stale animation callbacks without skipping the current gesture', () => {
    const welcome = createSentryWelcome(false, vi.fn())
    welcome.opened()
    welcome.cueFinished(1)
    welcome.cueFinished(3)
    expect(welcome.get().cue).toBe(2)
    welcome.lastReady()
    welcome.cueFinished(2)
    welcome.cueFinished(2)
    expect(welcome.get().cue).toBe(3)
  })
})
